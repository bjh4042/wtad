const originalChapter = (id: number): string => {
  if (id <= 6) return 'start';
  if (id <= 12) return 'display';
  if (id <= 22) return 'camera';
  if (id <= 29) return 'install';
  if (id <= 39 || id === 75) return 'quick';
  if (id <= 47) return 'notes';
  if (id <= 55) return 'notifications';
  if (id <= 74) return 'account';
  if (id <= 87) return 'calculator';
  return 'internet';
};

export const QUESTS: Quest[] = LESSONS.map(lesson => {
  const chapter = lesson.chapter ?? originalChapter(lesson.id);
  return { ...lesson, chapter, tip: lesson.tip ?? CHAPTERS.find(item => item.id === chapter)?.tip };
});

